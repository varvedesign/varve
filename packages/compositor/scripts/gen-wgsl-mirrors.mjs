#!/usr/bin/env node
/**
 * Generates the naga-validation mirrors for the live-effects WGSL kernels.
 *
 * The WGSL lives in TypeScript (packages/compositor/src/webgpu/effects/
 * kernels/*.ts, built as `WGSL_HELPERS + template`). This script extracts the
 * concatenated strings and regenerates the Rust consts in the family modules
 * under crates/varve-bridge/tests/wgsl_validation/, which naga compiles in
 * Rust CI - the cross-platform compile gate for the GPU shaders.
 *
 * Run after changing any effect kernel WGSL:
 *   node packages/compositor/scripts/gen-wgsl-mirrors.mjs
 *   cargo test -p varve-bridge --test wgsl_validation
 *
 * The compositor's wgsl-drift test keeps the TS and Rust copies in sync.
 * Only the nine generated family modules are written. The shared validate
 * helper, the hand-maintained shader mirrors and the crate-root test live in
 * the sibling modules and are never touched by this script.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const kernelsDir = join(root, 'packages', 'compositor', 'src', 'webgpu', 'effects', 'kernels');
const mirrorDir = join(root, 'crates', 'varve-bridge', 'tests', 'wgsl_validation');
const banner = '// Generated by packages/compositor/scripts/gen-wgsl-mirrors.mjs — do not edit.';

const KERNELS = [
  { id: 'rgbSplit', file: 'rgb_split.rs' },
  { id: 'crt', file: 'crt.rs' },
  { id: 'lightLeak', file: 'light_leak.rs' },
  { id: 'paletteSnap', file: 'palette_snap.rs' },
  { id: 'vhs', file: 'vhs.rs' },
  { id: 'lightShafts', file: 'light_shafts.rs' },
  { id: 'caustics', file: 'caustics.rs' },
  { id: 'lensFlare', file: 'lens_flare.rs' },
  { id: 'bloom', file: 'bloom.rs' },
];

function constNameFor(id) {
  return id.toUpperCase().replace(/[^A-Z0-9]/g, '_');
}

function extractHelpers() {
  const src = readFileSync(join(kernelsDir, 'shared.ts'), 'utf8');
  const m = src.match(/export const WGSL_HELPERS = \/\* wgsl \*\/ `([\s\S]*?)`;/);
  if (!m) throw new Error('WGSL_HELPERS not found in shared.ts');
  return m[1];
}

function extractKernelWgsl(kernelId) {
  const src = readFileSync(join(kernelsDir, `${kernelId}.ts`), 'utf8');
  // kernels use `WGSL_HELPERS + /* wgsl */ \`...\`` or a plain template;
  // rgbSplit concatenates two templates. Greedy capture to the FINAL
  // closing, then drop the ` + ` separators between the fragments.
  const pattern =
    /wgsl:\s*\n\s*(?:WGSL_HELPERS\s*\+\s*)?(?:\/\* wgsl \*\/ )?`\n([\s\S]*)\n`,\n {2}buildPasses/;
  const m = src.match(pattern);
  if (!m) throw new Error(`wgsl template not found for ${kernelId}`);
  return m[1].replace(/`\s*\+\s*\n\s*`/g, '');
}

const helpers = extractHelpers();
for (const kernel of KERNELS) {
  const body = extractKernelWgsl(kernel.id);
  const full = `${helpers}\n${body}`;
  const constName = `${constNameFor(kernel.id)}_WGSL`;
  const content = `${banner}\n\npub(crate) const ${constName}: &str = r#"${full}"#;\n`;
  const path = join(mirrorDir, kernel.file);
  writeFileSync(path, content);
  console.log(`wgsl mirror ${constName} -> ${kernel.file}`);
}
