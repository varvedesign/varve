#!/usr/bin/env node
/**
 * Generate the readable agent-parity coverage report from the machine-readable
 * manifest.
 *
 * The gate that *enforces* parity lives in
 * `packages/editor/src/automation/__tests__/agentParity.test.ts`, because only
 * there is the editor's real action inventory available (it is produced by
 * `createActionHandlers`). This script does not re-implement that check; it
 * renders the same numbers as a document a person can read, and `--check`
 * fails when the document on disk is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '../..');
const MANIFEST = resolve(REPO_ROOT, 'packages/automation/parity/agent-parity.json');
const REPORT = resolve(REPO_ROOT, 'docs/audits/agent-parity-coverage-2026-10-15.md');

/**
 * Name-based buckets, for readability only. A bucket says what an action looks
 * like it does; it is not a claim about its behaviour, and nothing in the gate
 * depends on it.
 */
const BUCKETS = [
  ['Typography and text', /^(text|editText|attachText|detachText|linkText|unlinkText)/],
  ['Layout and alignment', /^(align|distribute|tidy|harmonize|nudge|offsetPath|roundCorners)/],
  ['Vector geometry', /^(boolean|expandStroke|simplifyPath|pathTo|selectionTo|bakeWarp|flatten)/],
  ['Masking', /(Mask|mask)/],
  ['Masters and pages', /^(master|applyMaster|detachMaster|createMaster|auditPage|toolPage)/],
  ['Area selection', /^areaSelection/],
  ['Colour and palette', /(color|colour|Palette|palette|softProof|harmonize)/],
  ['Image and raster', /(Image|image|Raster|raster|Trace|trace|upscale|BgRemove|crop)/],
  ['Motion and timeline', /(Keyframe|keyframe|Timeline|timeline|play|stop|motion|onion|Graph)/],
  ['Logo and variants', /(Logo|logo|Variant|variant|Icon|icon)/],
  ['Presentation and prototype', /(present|Prototype|prototype|StateMachine|stateMachine)/],
  [
    'Panels and view',
    /(Panel|panel|Toolbar|toolbar|Grid|grid|Guide|guide|Minimap|minimap|canvasMode|inspectMode|zoom)/,
  ],
];

function bucket(id) {
  for (const [name, pattern] of BUCKETS) if (pattern.test(id)) return name;
  return 'Other document operations';
}

function main() {
  const check = process.argv.includes('--check');
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const inventory = manifest.inventoryAtCapture;
  const classified = new Set([
    ...Object.keys(manifest.reviewed),
    ...Object.keys(manifest.notACommand),
  ]);
  const backlog = inventory.filter((id) => !classified.has(id)).sort();

  const byReason = new Map();
  for (const reason of Object.values(manifest.notACommand)) {
    byReason.set(reason, (byReason.get(reason) ?? 0) + 1);
  }

  const buckets = new Map();
  for (const id of backlog) {
    const name = bucket(id);
    if (!buckets.has(name)) buckets.set(name, []);
    buckets.get(name).push(id);
  }

  const commands = Object.entries(manifest.commands).sort(([a], [b]) => a.localeCompare(b));
  const byCommand = new Map();
  for (const [action, command] of Object.entries(manifest.reviewed)) {
    if (!byCommand.has(command)) byCommand.set(command, []);
    byCommand.get(command).push(action);
  }

  const lines = [];
  lines.push('# Agent parity coverage (2026-10-15)');
  lines.push('');
  lines.push(
    'Generated by `node scripts/quality/agent-parity-report.mjs` from',
    '`packages/automation/parity/agent-parity.json`. The enforcing check is',
    '`packages/editor/src/automation/__tests__/agentParity.test.ts`; this document is the',
    'readable form of the same numbers and carries no separate authority.',
  );
  lines.push('');
  lines.push('## Denominators');
  lines.push('');
  lines.push('| Measure | Count |');
  lines.push('|---|---|');
  lines.push(`| Semantic commands registered | ${commands.length} |`);
  lines.push(`| Commands recorded in the manifest | ${Object.keys(manifest.commands).length} |`);
  lines.push(`| Editor actions that can be dispatched | ${inventory.length} |`);
  lines.push(`| Actions mapped to a command | ${Object.keys(manifest.reviewed).length} |`);
  lines.push(
    `| Actions recorded as "not a semantic command" | ${Object.keys(manifest.notACommand).length} |`,
  );
  lines.push(`| Actions with no command yet (backlog) | ${backlog.length} |`);
  lines.push('');
  lines.push(
    'The action count is the number of ids `createActionHandlers` really returns, so it',
    'counts parameterized tools and compound workflows as the separate routes they are. It',
    'is not a menu-item count, and a command that covers several routes is counted once in',
    '`commands` and once per route in `reviewed`.',
  );
  lines.push('');
  lines.push('## Commands and the UI routes they cover');
  lines.push('');
  lines.push('| Command | Status | Action-route coverage (enforced) | Tests |');
  lines.push('|---|---|---|---|');
  for (const [id, record] of commands) {
    const routes = (byCommand.get(id) ?? []).sort();
    const tests = record.tests.map((t) => `\`${t}\``).join('<br>');
    const surfaces = record.uiSurfaces ?? [];
    const cell =
      routes.length > 0
        ? routes.map((r) => `\`${r}\``).join('<br>')
        : surfaces.length > 0
          ? `no action route; reached by direct call (${surfaces.map((s) => `\`${s}\``).join(', ')})`
          : '—';
    lines.push(`| \`${id}\` | ${record.status} | ${cell} | ${tests} |`);
  }
  lines.push('');
  lines.push('## Recorded limits');
  lines.push('');
  for (const [id, record] of commands) {
    if (!record.limits || record.limits.length === 0) continue;
    lines.push(`- \`${id}\``);
    for (const limit of record.limits) lines.push(`  - ${limit}`);
  }
  lines.push('');
  lines.push('## Actions recorded as not being semantic commands');
  lines.push('');
  for (const [reason, count] of [...byReason.entries()].sort((a, b) => b[1] - a[1])) {
    const ids = Object.entries(manifest.notACommand)
      .filter(([, r]) => r === reason)
      .map(([id]) => id)
      .sort();
    lines.push(`### \`${reason}\` (${count})`);
    lines.push('');
    lines.push(ids.map((id) => `\`${id}\``).join(', '));
    lines.push('');
  }
  lines.push('## Unmapped backlog');
  lines.push('');
  lines.push(
    `Reason: \`${manifest.unmappedBacklog.reason}\`. Expires ${manifest.unmappedBacklog.expires},`,
    'after which the gate fails until the debt is paid or the expiry is deliberately extended.',
  );
  lines.push('');
  lines.push(manifest.unmappedBacklog.detail);
  lines.push('');
  for (const [name, ids] of [...buckets.entries()].sort((a, b) => b[1].length - a[1].length)) {
    lines.push(`### ${name} (${ids.length})`);
    lines.push('');
    lines.push(ids.map((id) => `\`${id}\``).join(', '));
    lines.push('');
  }
  lines.push('Buckets are name-based groupings for readability. They are not a claim about');
  lines.push('behaviour and nothing in the gate depends on them.');
  lines.push('');

  const rendered = lines.join('\n');
  if (check) {
    const onDisk = readFileSync(REPORT, 'utf8');
    if (onDisk !== rendered) {
      console.error(
        'agent-parity report is stale; run: node scripts/quality/agent-parity-report.mjs',
      );
      process.exit(1);
    }
    console.log(`agent-parity report is current (${inventory.length} actions)`);
    return;
  }
  writeFileSync(REPORT, rendered);
  console.log(`wrote ${REPORT} (${inventory.length} actions, ${backlog.length} unmapped)`);
}

main();
