#!/usr/bin/env node
/**
 * Generate packages/shared/src/verticalOrientationData.ts from the Unicode
 * Vertical_Orientation data file (UAX #50).
 *
 * Usage:
 *   curl -o /tmp/VerticalOrientation.txt \
 *     https://www.unicode.org/Public/16.0.0/ucd/VerticalOrientation.txt
 *   node scripts/generate-vertical-orientation.mjs /tmp/VerticalOrientation.txt
 *
 * The generated module is committed, so this script only needs to run when
 * the pinned UCD version is upgraded. Output values: 0 = U (upright),
 * 1 = R (rotated), 2 = Tu (transformed, upright fallback), 3 = Tr
 * (transformed, rotated fallback). Ranges not listed default to R per the
 * file's @missing line; the header's unassigned-default-U ranges are folded
 * into the table so private-use CJK and future CJK blocks resolve upright.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [, , inputPath = '/tmp/VerticalOrientation.txt'] = process.argv;
const text = readFileSync(inputPath, 'utf8');

const missing = text.match(/^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)$/m);
if (missing?.[3] !== 'R') {
  throw new Error('Unexpected @missing default; regenerate against the pinned format');
}

const version = text.match(/^# VerticalOrientation-([\d.]+)\.txt$/m);
const date = text.match(/^# Date: (.+),/m);
if (!version || !date) throw new Error('Could not read UCD version/date header');

const VALUES = { U: 0, R: 1, Tu: 2, Tr: 3 };

const ranges = [];
for (const line of text.split('\n')) {
  const data = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(U|R|Tu|Tr)\s*(?:#|$)/);
  if (data) {
    ranges.push([parseInt(data[1], 16), parseInt(data[2] ?? data[1], 16), VALUES[data[3]]]);
  }
}
if (ranges.length < 2000) throw new Error(`Only ${ranges.length} ranges parsed; file truncated?`);

// Unassigned code points that default to U (documented in the file header).
// They are absent from the data section because they are unassigned, but
// private-use and not-yet-assigned CJK blocks must resolve upright.
const HEADER_DEFAULT_U = [
  [0x18b0, 0x18ff],
  [0x2065, 0x2065],
  [0x2150, 0x218f],
  [0x2400, 0x245f],
  [0x2bb8, 0x2bff],
  [0x2e80, 0xa4cf],
  [0xa960, 0xa97f],
  [0xac00, 0xd7ff],
  [0xe000, 0xfaff],
  [0xfe10, 0xfe1f],
  [0xfe50, 0xfe6f],
  [0xffe7, 0xffe7],
  [0xfff0, 0xfff8],
  [0x11580, 0x115ff],
  [0x11a00, 0x11aaf],
  [0x13000, 0x143ff],
  [0x14400, 0x1467f],
  [0x16fe0, 0x18aff],
  [0x18b00, 0x18d7f],
  [0x1aff0, 0x1afff],
  [0x1b100, 0x1b16f],
  [0x1b170, 0x1b2ff],
  [0x1cf00, 0x1cfcf],
  [0x1d000, 0x1d1ff],
  [0x1d2e0, 0x1d2ff],
  [0x1d300, 0x1d37f],
  [0x1d800, 0x1daaf],
  [0x1f000, 0x1f0ff],
  [0x1f100, 0x1f2ff],
  [0x1f680, 0x1f7ff],
  [0x1f900, 0x1f9ff],
  [0x1fa00, 0x1faff],
  [0x20000, 0x2fffd],
  [0x30000, 0x3fffd],
  [0xf0000, 0xffffd],
  [0x100000, 0x10fffd],
];
for (const [start, end] of HEADER_DEFAULT_U) ranges.push([start, end, VALUES.U]);

ranges.sort((a, b) => a[0] - b[0] || b[1] - a[1]);

// Merge overlapping/adjacent ranges that share a value so lookup stays tight.
const merged = [];
for (const [start, end, value] of ranges) {
  const last = merged[merged.length - 1];
  if (last && last[2] === value && start <= last[1] + 1) {
    last[1] = Math.max(last[1], end);
  } else {
    merged.push([start, end, value]);
  }
}

const hex = (n) => `0x${n.toString(16).padStart(4, '0')}`;
const rows = merged.map(([s, e, v]) => `  [${hex(s)}, ${hex(e)}, ${v}]`).join(',\n');

const out = `/**
 * Generated by scripts/generate-vertical-orientation.mjs — do not edit.
 *
 * Source: Unicode Character Database VerticalOrientation-${version[1]}.txt
 * (${date[1]} GMT), https://www.unicode.org/reports/tr50/
 * Unicode terms of use: https://www.unicode.org/terms_of_use.html
 *
 * Flat [firstCodePoint, lastCodePoint, value] ranges, sorted ascending.
 * Value 0 = U (upright), 1 = R (rotated a quarter turn clockwise),
 * 2 = Tu (transformed, upright fallback), 3 = Tr (transformed, rotated
 * fallback). Code points not present default to R, per the data file's
 * \`@missing: 0000..10FFFF; R\` line; unassigned ranges that the file header
 * defaults to U (private-use CJK, planes 2-3, future CJK blocks) are folded
 * in as explicit U entries.
 */

export const VERTICAL_ORIENTATION_UCD_VERSION = '${version[1]}';

export const VERTICAL_ORIENTATION_RANGES: readonly (readonly [number, number, number])[] = [
${rows},
];
`;

writeFileSync(new URL('../packages/shared/src/verticalOrientationData.ts', import.meta.url), out);
console.log(
  `verticalOrientationData.ts: ${merged.length} ranges from UCD ${version[1]} (${ranges.length - merged.length} merged)`,
);
